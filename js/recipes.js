// 단계 이름 (레시피 카드에 보이는 글자)
function stepName(st) {
  if (st.label) return st.label;
  if (st.type === 'pour') return `${st.item} ${st.target}${st.unit}`;
  if (st.type === 'add') return `${st.item} 넣기`;
  return st.item || '';
}

// 레시피 찾기 (없으면 예전 간단 레시피로 만들기)
function getRecipe(shop, good) {
  const r = RECIPES[shop.name] && RECIPES[shop.name][good[1]];
  if (r) return r;
  return (good[3] || []).map(st => /(기|질|포장)$/.test(st.name)
    ? { type: 'mix', label: st.name, icon: st.icon, zone: 'bench' }
    : { type: 'add', item: st.name, icon: st.icon, zone: 'bench' });
}
